// O 'let' cria uma variável cujo valor pode mudar depois
let nome = "Esmael"; 
let idade = 16;

// O 'const' cria uma constante (um valor fixo que NÃO pode mudar)
const pi = 3.14159;

// O 'var' é a forma mais antiga de declarar variáveis (evite usar em códigos modernos, prefira 'let')
var cidade = "São Paulo";

// Tipos de dados comuns:
let texto = "Olá, mundo!"; // String (texto entre aspas)
let numeroInteiro = 25; // Number (números inteiros ou decimais)
let estaLogado = true; // Boolean (verdadeiro ou falso -> true/false)